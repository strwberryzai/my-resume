let currentLanguage = 'es';

const languageFlags = {
    es: '🇪🇸',
    en: '🇺🇸',
    fr: '🇫🇷'
};

function updateLanguage(lang) {
    currentLanguage = lang;
    
    
    document.getElementById('currentFlag').textContent = languageFlags[lang];
    
    
    document.querySelectorAll('.language-option').forEach(option => {
        option.classList.toggle('active', option.dataset.lang === lang);
    });
    
    
    updateTranslations();
    
    
    updateProjectContent();
    

    localStorage.setItem('preferredLanguage', lang);
}

function updateTranslations() {
    const t = translations[currentLanguage];
    
    
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.dataset.translate;
        const keys = key.split('.');
        let value = t;
        
        keys.forEach(k => {
            if (value && value[k]) {
                value = value[k];
            }
        });
        
        if (typeof value === 'string') {
            element.textContent = value;
        }
    });
    
    
    const heroBadge = document.querySelector('.hero-badge span');
    if (heroBadge) heroBadge.textContent = t.hero.badge;
    
    const titleLine = document.querySelector('.title-line');
    if (titleLine) titleLine.textContent = t.hero.title.line1;
    
    const titleGradient = document.querySelector('.title-gradient');
    if (titleGradient) titleGradient.textContent = t.hero.title.name;
    
    const heroTitle = document.querySelector('.hero-title');
    if (heroTitle) {
        const thirdLine = heroTitle.querySelector('span:nth-child(3)') || 
                         heroTitle.appendChild(document.createElement('span'));
        thirdLine.className = 'title-line';
        thirdLine.textContent = t.hero.title.line2;
    }
    
    const heroDescription = document.querySelector('.hero-description');
    if (heroDescription) heroDescription.textContent = t.hero.description;
    
    const heroButtons = document.querySelectorAll('.hero-buttons .btn');
    if (heroButtons.length >= 2) {
        heroButtons[0].textContent = t.hero.buttons.projects;
        heroButtons[1].textContent = t.hero.buttons.contact;
    }
    
    // About section - fixed ID to match HTML
    const aboutTitle = document.querySelector('#sobre-mí .section-header h2');
    if (aboutTitle) aboutTitle.textContent = t.about.title;
    
    const aboutDescription = document.querySelector('.about-card p');
    if (aboutDescription) aboutDescription.textContent = t.about.description;
    
    
    const projectsTitle = document.querySelector('#proyectos .section-header h2');
    if (projectsTitle) projectsTitle.textContent = t.projects.title;
    
    const projectsSubtitle = document.querySelector('#proyectos .section-subtitle');
    if (projectsSubtitle) projectsSubtitle.textContent = t.projects.subtitle;
    
    
    const skillsTitle = document.querySelector('#habilidades .section-header h2');
    if (skillsTitle) skillsTitle.textContent = t.skills.title;
    
    const skillsSubtitle = document.querySelector('#habilidades .section-subtitle');
    if (skillsSubtitle) skillsSubtitle.textContent = t.skills.subtitle;
    
    
    const contactTitle = document.querySelector('#contacto .section-header h2');
    if (contactTitle) contactTitle.textContent = t.contact.title;
    
    const contactSubtitle = document.querySelector('#contacto .section-subtitle');
    if (contactSubtitle) contactSubtitle.textContent = t.contact.subtitle;
    
    const ctaButton = document.querySelector('.contact-cta .btn');
    if (ctaButton) ctaButton.textContent = t.contact.cta;
    
    
    const footer = document.querySelector('.footer p');
    if (footer) {
        footer.innerHTML = t.footer.replace('❤️', '<span class="heart">♥</span>');
    }
}

function updateProjectContent() {
    const t = translations[currentLanguage];
    
    
    projects = t.projects.items.map((item, index) => ({
        title: item.title,
        description: item.description,
        tech: item.tech,
        gradient: projectGradients[index] || "from-pink-300 to-rose-300"
    }));
    
    
    generateCarouselContent();
}


const projectGradients = [
    "from-pink-300 to-rose-300",
    "from-purple-300 to-pink-300", 
    "from-blue-300 to-purple-300",
    "from-green-300 to-blue-300"
];

let projects = [];

let currentSlide = 0;
let autoplayInterval;

function initCarousel() {
    const track = document.getElementById('carouselTrack');
    const thumbnailsContainer = document.getElementById('carouselThumbnails');

    // Clear existing content
    track.innerHTML = '';
    thumbnailsContainer.innerHTML = '';
    
    // Generate carousel content
    projects.forEach((project, index) => {
        const nextColor = projectColors[(index + 1) % projectColors.length];
        
        // Create slide
        const slide = document.createElement('div');
        slide.className = `carousel-slide ${index === 0 ? 'active' : ''}`;
        slide.style.background = `linear-gradient(135deg, ${project.gradient}, ${nextColor})`;
        
        const overlay = document.createElement('div');
        overlay.className = 'carousel-overlay';
        slide.appendChild(overlay);
        
        track.appendChild(slide);

        // Create thumbnail
        const thumbnail = document.createElement('button');
        thumbnail.className = `carousel-thumbnail ${index === 0 ? 'active' : ''}`;
        thumbnail.style.background = `linear-gradient(135deg, ${project.gradient}, ${nextColor})`;
        thumbnail.addEventListener('click', () => goToSlide(index));
        thumbnailsContainer.appendChild(thumbnail);
    });

    document.getElementById('prevBtn').addEventListener('click', () => {
        goToSlide(currentSlide - 1);
        resetAutoplay();
    });

    document.getElementById('nextBtn').addEventListener('click', () => {
        goToSlide(currentSlide + 1);
        resetAutoplay();
    });

    startAutoplay();
}

function goToSlide(index) {
    const slides = document.querySelectorAll('.carousel-slide');
    const thumbnails = document.querySelectorAll('.carousel-thumbnail');

    // Wrap around
    if (index < 0) index = slides.length - 1;
    if (index >= slides.length) index = 0;

    // Remove active classes
    slides.forEach(slide => slide.classList.remove('active'));
    thumbnails.forEach(thumb => thumb.classList.remove('active'));

    // Add active classes
    slides[index].classList.add('active');
    thumbnails[index].classList.add('active');

    currentSlide = index;
}

function nextSlide() {
    goToSlide(currentSlide + 1);
}

function startAutoplay() {
    autoplayInterval = setInterval(nextSlide, 4000);
}

function resetAutoplay() {
    clearInterval(autoplayInterval);
    startAutoplay();
}


function setupIntersectionObservers() {
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
                // For skill bubbles, we don't need to do anything extra
                // as they animate on their own with CSS
            }
        });
    }, observerOptions);

    
    document.querySelectorAll('.section-header').forEach(header => {
        observer.observe(header);
    });

   
    const aboutCard = document.querySelector('.about-card-wrapper');
    if (aboutCard) observer.observe(aboutCard);

    
    document.querySelectorAll('.skill-bubble').forEach(bubble => {
        observer.observe(bubble);
    });

    document.querySelectorAll('.contact-card').forEach(card => {
        observer.observe(card);
    });
}



function setupSmoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                const navHeight = document.querySelector('.navbar').offsetHeight;
                const targetPosition = target.offsetTop - navHeight;
                
                window.scrollTo({
                    top: targetPosition,
                    behavior: 'smooth'
                });
            }
        });
    });
}


function setupActiveNavigation() {
    const sections = document.querySelectorAll('section[id]');
    const navLinks = document.querySelectorAll('.nav-link');

    function updateActiveLink() {
        const scrollPosition = window.scrollY + 100;

        sections.forEach(section => {
            const sectionTop = section.offsetTop;
            const sectionHeight = section.offsetHeight;
            const sectionId = section.getAttribute('id');

            if (scrollPosition >= sectionTop && scrollPosition < sectionTop + sectionHeight) {
                navLinks.forEach(link => {
                    link.classList.remove('active');
                    if (link.getAttribute('href') === `#${sectionId}`) {
                        link.classList.add('active');
                    }
                });
            }
        });
    }

    window.addEventListener('scroll', updateActiveLink);
    updateActiveLink(); // Call once on load
}


function setupKeyboardNavigation() {
    document.addEventListener('keydown', (e) => {
        if (e.key === 'ArrowLeft') {
            goToSlide(currentSlide - 1);
            resetAutoplay();
        } else if (e.key === 'ArrowRight') {
            goToSlide(currentSlide + 1);
            resetAutoplay();
        }
    });
}


function setupCarouselHoverPause() {
    const carouselMain = document.querySelector('.carousel-main');
    
    carouselMain.addEventListener('mouseenter', () => {
        clearInterval(autoplayInterval);
    });

    carouselMain.addEventListener('mouseleave', () => {
        startAutoplay();
    });
}



document.addEventListener('DOMContentLoaded', () => {
   
    initLanguageSelector();
    
   
    const preferredLanguage = localStorage.getItem('preferredLanguage');
    if (preferredLanguage) {
        updateLanguage(preferredLanguage);
    } else {
        updateLanguage(currentLanguage);
    }

    initCarousel();
    setupIntersectionObservers();
    setupSmoothScroll();
    setupActiveNavigation();
    setupKeyboardNavigation();
    setupCarouselHoverPause();
    
    
    document.body.classList.add('loaded');
    
    console.log('Portfolio de Ana Camila Mondragón Rivera cargado exitosamente! 💖');
});



function initLanguageSelector() {
    const languageBtn = document.getElementById('languageBtn');
    const languageDropdown = document.getElementById('languageDropdown');
    const languageOptions = document.querySelectorAll('.language-option');
    
    languageBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        languageDropdown.classList.toggle('active');
    });
    
   
    document.addEventListener('click', (e) => {
        if (!languageBtn.contains(e.target) && !languageDropdown.contains(e.target)) {
            languageDropdown.classList.remove('active');
        }
    });
    
  
    languageOptions.forEach(option => {
        option.addEventListener('click', (e) => {
            e.stopPropagation();
            const selectedLang = option.dataset.lang;
            updateLanguage(selectedLang);
            languageDropdown.classList.remove('active');
        });
    });
    
   
    languageOptions.forEach(option => {
        option.classList.toggle('active', option.dataset.lang === currentLanguage);
    });
}

const projectColors = [
    '#f4a6d7',
    '#fbb8df', 
    '#ffd4e9',
    '#fce4f0'
];

function generateCarouselContent() {
    const track = document.getElementById('carouselTrack');
    const thumbnailsContainer = document.getElementById('carouselThumbnails');
    
    track.innerHTML = '';
    thumbnailsContainer.innerHTML = '';
    
    projects.forEach((project, index) => {
        // Create slide
        const slide = document.createElement('div');
        slide.className = `carousel-slide ${index === 0 ? 'active' : ''}`;
        
        // Convert Tailwind-style gradients to CSS
        let gradientCSS;
        switch(project.gradient) {
            case "from-pink-300 to-rose-300":
                gradientCSS = "linear-gradient(135deg, #f9a8d4, #fda4af)";
                break;
            case "from-purple-300 to-pink-300":
                gradientCSS = "linear-gradient(135deg, #d8b4fe, #f9a8d4)";
                break;
            case "from-blue-300 to-purple-300":
                gradientCSS = "linear-gradient(135deg, #93c5fd, #d8b4fe)";
                break;
            case "from-green-300 to-blue-300":
                gradientCSS = "linear-gradient(135deg, #86efac, #93c5fd)";
                break;
            default:
                gradientCSS = "linear-gradient(135deg, #f9a8d4, #fda4af)";
        }
        
        slide.style.background = gradientCSS;
        
        // Create content overlay
        const content = document.createElement('div');
        content.style.cssText = `
            position: absolute;
            bottom: 2rem;
            left: 2rem;
            right: 2rem;
            color: white;
            background: rgba(255, 255, 255, 0.1);
            backdrop-filter: blur(10px);
            padding: 2rem;
            border-radius: 1rem;
        `;
        
        const title = document.createElement('h3');
        title.textContent = project.title;
        title.style.cssText = `
            font-size: 1.5rem;
            font-weight: bold;
            margin-bottom: 1rem;
        `;
        
        const description = document.createElement('p');
        description.textContent = project.description;
        description.style.cssText = `
            margin-bottom: 1rem;
            line-height: 1.6;
        `;
        
        const techList = document.createElement('div');
        techList.style.cssText = `
            display: flex;
            flex-wrap: wrap;
            gap: 0.5rem;
        `;
        
        project.tech.forEach(tech => {
            const techBadge = document.createElement('span');
            techBadge.textContent = tech;
            techBadge.style.cssText = `
                background: rgba(255, 255, 255, 0.2);
                padding: 0.25rem 0.5rem;
                border-radius: 0.5rem;
                font-size: 0.875rem;
            `;
            techList.appendChild(techBadge);
        });
        
        content.appendChild(title);
        content.appendChild(description);
        content.appendChild(techList);
        slide.appendChild(content);
        
        const overlay = document.createElement('div');
        overlay.className = 'carousel-overlay';
        slide.appendChild(overlay);
        
        track.appendChild(slide);

        // Create thumbnail
        const thumbnail = document.createElement('button');
        thumbnail.className = `carousel-thumbnail ${index === 0 ? 'active' : ''}`;
        thumbnail.style.background = gradientCSS;
        thumbnail.addEventListener('click', () => goToSlide(index));
        thumbnailsContainer.appendChild(thumbnail);
    });
}


